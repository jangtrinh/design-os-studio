use crate::theme;
use egui::Color32;

pub(super) fn token(name: &str) -> Color32 {
    match name {
        "BADGE_NEUTRAL_BG" => theme::BADGE_NEUTRAL_BG,
        "BADGE_NEUTRAL_BORDER" => theme::BADGE_NEUTRAL_BORDER,
        "BADGE_NEUTRAL_TEXT" => theme::BADGE_NEUTRAL_TEXT,
        "BG" => theme::BG,
        "BG_BRAND" => theme::BG_BRAND,
        "BG_BRAND_HOVER" => theme::BG_BRAND_HOVER,
        "BG_BRAND_PRESSED" => theme::BG_BRAND_PRESSED,
        "BG_ERROR_PRIMARY" => theme::BG_ERROR_PRIMARY,
        "BG_ERROR_SOLID" => theme::BG_ERROR_SOLID,
        "BG_ERROR_SOLID_HOVER" => theme::BG_ERROR_SOLID_HOVER,
        "BG_ERROR_SOLID_PRESSED" => theme::BG_ERROR_SOLID_PRESSED,
        "BG_HOVER" => theme::BG_HOVER,
        "BG_PRESSED" => theme::BG_PRESSED,
        "BG_PRIMARY_ALT" => theme::BG_PRIMARY_ALT,
        "BG_PRIMARY_SOLID" => theme::BG_PRIMARY_SOLID,
        "BG_SECONDARY" => theme::BG_SECONDARY,
        "BG_SELECTED" => theme::BG_SELECTED,
        "BG_TERTIARY" => theme::BG_TERTIARY,
        "BORDER" => theme::BORDER,
        "BORDER_ERROR" => theme::BORDER_ERROR,
        "BORDER_ERROR_SUBTLE" => theme::BORDER_ERROR_SUBTLE,
        "BORDER_MENU" => theme::BORDER_MENU,
        "BORDER_SELECTED" => theme::BORDER_SELECTED,
        "BORDER_STRONG" => theme::BORDER_STRONG,
        "BORDER_TRANSLUCENT" => theme::BORDER_TRANSLUCENT,
        "FOCUS_RING" => theme::FOCUS_RING,
        "FOCUS_RING_ERROR" => theme::FOCUS_RING_ERROR,
        "ICON" => theme::ICON,
        "ICON_BRAND_PRIMARY" => theme::ICON_BRAND_PRIMARY,
        "ICON_QUATERNARY" => theme::ICON_QUATERNARY,
        "ICON_QUATERNARY_HOVER" => theme::ICON_QUATERNARY_HOVER,
        "ICON_SECONDARY" => theme::ICON_SECONDARY,
        "ICON_SECONDARY_HOVER" => theme::ICON_SECONDARY_HOVER,
        "ICON_WHITE" => theme::ICON_WHITE,
        "TEXT" => theme::TEXT,
        "TEXT_ERROR" => theme::TEXT_ERROR,
        "TEXT_ERROR_HOVER" => theme::TEXT_ERROR_HOVER,
        "TEXT_ON_BRAND" => theme::TEXT_ON_BRAND,
        "TEXT_PLACEHOLDER" => theme::TEXT_PLACEHOLDER,
        "TEXT_QUATERNARY" => theme::TEXT_QUATERNARY,
        "TEXT_SECONDARY" => theme::TEXT_SECONDARY,
        "TEXT_SECONDARY_HOVER" => theme::TEXT_SECONDARY_HOVER,
        "TEXT_TERTIARY" => theme::TEXT_TERTIARY,
        "TEXT_TERTIARY_HOVER" => theme::TEXT_TERTIARY_HOVER,
        "TEXT_WHITE" => theme::TEXT_WHITE,
        other => panic!("stopped, missing constant {other}"),
    }
}
