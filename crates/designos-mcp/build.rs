use std::{
    env, fs,
    path::{Path, PathBuf},
};

const SURFACE_TOPICS: &[&str] = &["code", "design-system-guide", "landing-page", "mobile-app", "slides", "table", "tailwind", "web-app"];

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let guidelines_dir = manifest_dir.join("guidelines");
    let surfaces_dir = guidelines_dir.join("surfaces");
    let archetypes_dir = guidelines_dir.join("archetypes");
    let rules_file = guidelines_dir.join("rules.md");

    println!("cargo:rerun-if-changed={}", guidelines_dir.display());
    println!("cargo:rerun-if-changed={}", surfaces_dir.display());
    println!("cargo:rerun-if-changed={}", archetypes_dir.display());
    println!("cargo:rerun-if-changed={}", rules_file.display());

    let mut code = String::from("// @generated by crates/designos-mcp/build.rs — embeds guidelines/** with include_str!\n");

    code.push_str("pub const EMBEDDED_SURFACES: &[(&str, Option<&str>)] = &[\n");
    for topic in SURFACE_TOPICS {
        let p = surfaces_dir.join(format!("{topic}.md"));
        println!("cargo:rerun-if-changed={}", p.display());
        if p.is_file() {
            let escaped = escape_path(&p);
            code.push_str(&format!("    ({topic:?}, Some(include_str!(\"{escaped}\"))),\n"));
        } else {
            code.push_str(&format!("    ({topic:?}, None),\n"));
        }
    }
    code.push_str("];\n\n");

    let mut arch_files: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(entries) = fs::read_dir(&archetypes_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|x| x.to_str()) == Some("toml") {
                if let Some(stem) = path.file_stem().and_then(|s| s.to_str()) {
                    println!("cargo:rerun-if-changed={}", path.display());
                    arch_files.push((stem.to_string(), path));
                }
            }
        }
    }
    arch_files.sort_by(|a, b| a.0.cmp(&b.0));

    code.push_str("pub const EMBEDDED_ARCHETYPES: &[(&str, &str)] = &[\n");
    for (stem, path) in &arch_files {
        let escaped = escape_path(path);
        code.push_str(&format!("    ({stem:?}, include_str!(\"{escaped}\")),\n"));
    }
    code.push_str("];\n\n");

    if rules_file.is_file() {
        let escaped = escape_path(&rules_file);
        code.push_str(&format!("pub const EMBEDDED_RULES: Option<&str> = Some(include_str!(\"{escaped}\"));\n"));
    } else {
        code.push_str("pub const EMBEDDED_RULES: Option<&str> = None;\n");
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("embedded_guidelines.rs"), code).expect("write embedded_guidelines.rs");
}

fn escape_path(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "\\\\").replace('"', "\\\"")
}
