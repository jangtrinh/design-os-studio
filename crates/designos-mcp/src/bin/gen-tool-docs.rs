use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use serde_json::Value;

pub const BEGIN_MARKER: &str = "<!-- designos-mcp-tools:begin -->";
pub const END_MARKER: &str = "<!-- designos-mcp-tools:end -->";

pub const DOC_TARGETS: &[&str] = &["README.md", "CLAUDE.md", "skills/design-os-studio/SKILL.md"];

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolSnapshot {
    pub name: String,
    pub description: String,
    #[serde(rename = "inputSchema")]
    pub input_schema: Value,
    pub annotations: BTreeMap<String, Value>,
}

impl ToolSnapshot {
    pub fn required_args(&self) -> Vec<String> {
        let mut req: Vec<String> = self.input_schema["required"].as_array().into_iter().flatten().filter_map(|v| v.as_str().map(str::to_string)).collect();
        req.sort();
        req
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ParityFile {
    pub figma_docs_url: String,
    pub retrieved: String,
    pub core_tools: usize,
    pub weave_tools: usize,
    pub rows: Vec<ParityRow>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ParityRow {
    pub figma_tool: String,
    pub status: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub studio_tool: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub task_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
}

pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().and_then(Path::parent).expect("crates/designos-mcp must live two levels below workspace root").to_path_buf()
}

fn canonicalize_schema_value(val: &Value, key_hint: Option<&str>) -> Value {
    match val {
        Value::Object(map) => {
            let mut sorted: BTreeMap<String, Value> = BTreeMap::new();
            for (k, v) in map {
                sorted.insert(k.clone(), canonicalize_schema_value(v, Some(k.as_str())));
            }
            let mut out = serde_json::Map::new();
            for (k, v) in sorted {
                out.insert(k, v);
            }
            Value::Object(out)
        }
        Value::Array(arr) => {
            let mut items: Vec<Value> = arr.iter().map(|v| canonicalize_schema_value(v, None)).collect();
            if key_hint == Some("required") && items.iter().all(Value::is_string) {
                items.sort_by(|a, b| a.as_str().cmp(&b.as_str()));
            }
            Value::Array(items)
        }
        other => other.clone(),
    }
}

pub fn build_tool_snapshots() -> Vec<ToolSnapshot> {
    designos_mcp::server::tools()
        .into_iter()
        .map(|rmcp_tool| {
            let tool = serde_json::to_value(&rmcp_tool).expect("serialize rmcp Tool");
            let name = tool["name"].as_str().expect("tool must have string name").to_string();
            let description = tool["description"].as_str().expect("tool must have string description").to_string();
            let mut raw_schema = tool.get("inputSchema").expect("tool must have inputSchema").clone();
            if let Some(obj) = raw_schema.as_object_mut() {
                obj.entry("required").or_insert_with(|| serde_json::json!([]));
            }
            assert!(raw_schema["required"].is_array(), "inputSchema.required must be array");
            assert!(raw_schema["properties"].is_object(), "inputSchema.properties must be object");
            let input_schema = canonicalize_schema_value(&raw_schema, None);

            let annotations: BTreeMap<String, Value> =
                tool["annotations"].as_object().expect("annotations must be object").iter().map(|(k, v)| (k.clone(), v.clone())).collect();

            ToolSnapshot { name, description, input_schema, annotations }
        })
        .collect()
}

pub fn render_tools_snapshot_json(snapshots: &[ToolSnapshot]) -> String {
    let mut json = serde_json::to_string_pretty(snapshots).expect("serialize tool snapshots");
    json.push('\n');
    json
}

pub fn escape_md_cell(text: &str) -> String {
    text.replace('\r', "").replace('\n', " ").replace('|', "\\|")
}

pub fn render_tools_markdown_block(snapshots: &[ToolSnapshot]) -> String {
    let mut out = String::new();
    out.push_str(BEGIN_MARKER);
    out.push('\n');
    out.push_str("<!-- Generated by `cargo run -p designos-mcp --bin gen-tool-docs`. Do not edit by hand. -->\n\n");
    out.push_str(&format!("| Tool (`{}` total) | Mode | Required Args | Description |\n", snapshots.len()));
    out.push_str("| --- | --- | --- | --- |\n");
    for tool in snapshots {
        let read_only = tool.annotations.get("readOnlyHint").and_then(Value::as_bool).unwrap_or(false);
        let mode = if read_only { "read-only" } else { "mutating" };
        let required = tool.required_args();
        let req =
            if required.is_empty() { "—".to_string() } else { required.iter().map(|r| format!("`{}`", escape_md_cell(r))).collect::<Vec<_>>().join(", ") };
        out.push_str(&format!("| `{}` | {} | {} | {} |\n", escape_md_cell(&tool.name), mode, req, escape_md_cell(&tool.description),));
    }
    out.push_str(END_MARKER);
    out
}

pub fn replace_marked_block(content: &str, generated_block: &str) -> Result<String, String> {
    let begin_idx = content.find(BEGIN_MARKER).ok_or_else(|| format!("missing `{BEGIN_MARKER}` marker"))?;
    let end_rel = content[begin_idx..].find(END_MARKER).ok_or_else(|| format!("missing `{END_MARKER}` marker after begin marker"))?;
    let end_idx = begin_idx + end_rel + END_MARKER.len();

    let mut updated = String::with_capacity(content.len() + generated_block.len());
    updated.push_str(&content[..begin_idx]);
    updated.push_str(generated_block);
    updated.push_str(&content[end_idx..]);
    Ok(updated)
}

pub fn render_parity_markdown(snapshots: &[ToolSnapshot], parity: &ParityFile) -> String {
    let implemented_count = parity.rows.iter().filter(|r| r.status == "implemented").count();
    let task_count = parity.rows.iter().filter(|r| r.status == "task").count();
    let excluded_count = parity.rows.iter().filter(|r| r.status == "excluded").count();

    let mut out = String::new();
    out.push_str("# DESIGN:OS Studio MCP Tool Catalog & Figma Parity Matrix\n\n");
    out.push_str("<!-- Generated by `cargo run -p designos-mcp --bin gen-tool-docs`. Do not edit by hand. -->\n\n");
    out.push_str(&format!(
        "- **Studio Declared MCP Tools**: `{}` (`4` session tools + `{}` engine tools) + `{}` legacy aliases\n",
        snapshots.len(),
        designos_mcp::engine::tools().len(),
        designos_mcp::engine::ALIASES.len()
    ));
    out.push_str(&format!("- **Figma MCP Reference**: <{}> (retrieved `{}`)\n", parity.figma_docs_url, parity.retrieved));
    out.push_str(&format!(
        "- **Figma Surface Coverage**: `{}` total (`{}` core + `{}` Weave) — `{}` implemented, `{}` tracked by roadmap task, `{}` excluded by owner ruling\n\n",
        parity.rows.len(),
        parity.core_tools,
        parity.weave_tools,
        implemented_count,
        task_count,
        excluded_count
    ));

    out.push_str("## 1. DESIGN:OS Studio Declared Tools\n\n");
    out.push_str(&render_tools_markdown_block(snapshots));
    out.push_str("\n\n### Compatibility Aliases (`Engine::ALIASES`)\n\n");
    out.push_str("| Alias | Canonical Tool |\n");
    out.push_str("| --- | --- |\n");
    for &alias in designos_mcp::engine::ALIASES {
        let canonical = match alias {
            "export_fig_file" => "designos_export_fig_file",
            "get_guidelines" => "designos_get_guidelines",
            "get_metadata" => "designos_get_metadata",
            "query_nodes" => "designos_query_xpath",
            "check_design" => "designos_lint",
            other => other,
        };
        out.push_str(&format!("| `{}` | `{}` |\n", escape_md_cell(alias), escape_md_cell(canonical)));
    }

    out.push_str("\n## 2. Figma MCP Parity Matrix\n\n");
    out.push_str("| # | Figma Tool | Status | Studio Tool / Task / Ruling | Notes |\n");
    out.push_str("| --- | --- | --- | --- | --- |\n");
    for (idx, row) in parity.rows.iter().enumerate() {
        let target = match row.status.as_str() {
            "implemented" => row.studio_tool.as_deref().map(|s| format!("`{}`", escape_md_cell(s))).unwrap_or_else(|| "—".to_string()),
            "task" => row.task_id.as_deref().map(|t| format!("`{}`", escape_md_cell(t))).unwrap_or_else(|| "—".to_string()),
            "excluded" => row.reason.as_deref().map(escape_md_cell).unwrap_or_else(|| "—".to_string()),
            other => escape_md_cell(other),
        };
        let note = row.note.as_deref().or(row.reason.as_deref()).map(escape_md_cell).unwrap_or_else(|| "—".to_string());
        out.push_str(&format!("| {} | `{}` | `{}` | {} | {} |\n", idx + 1, escape_md_cell(&row.figma_tool), escape_md_cell(&row.status), target, note,));
    }

    out
}

#[allow(dead_code)]
fn main() {
    let root = repo_root();
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));

    let snapshots = build_tool_snapshots();
    let snapshot_json = render_tools_snapshot_json(&snapshots);
    let snapshot_path = crate_dir.join("tests/snapshots/tools.json");
    if let Some(parent) = snapshot_path.parent() {
        fs::create_dir_all(parent).expect("create tests/snapshots dir");
    }
    fs::write(&snapshot_path, snapshot_json).expect("write tests/snapshots/tools.json");

    let parity_path = crate_dir.join("parity/figma-mcp-parity.json");
    let parity_raw = fs::read_to_string(&parity_path).expect("read parity/figma-mcp-parity.json");
    let parity: ParityFile = serde_json::from_str(&parity_raw).expect("parse parity/figma-mcp-parity.json");

    let parity_md = render_parity_markdown(&snapshots, &parity);
    let parity_doc_path = root.join("docs/mcp-parity.md");
    if let Some(parent) = parity_doc_path.parent() {
        fs::create_dir_all(parent).expect("create docs dir");
    }
    fs::write(&parity_doc_path, parity_md).expect("write docs/mcp-parity.md");

    let block = render_tools_markdown_block(&snapshots);
    for rel in DOC_TARGETS {
        let path = root.join(rel);
        let original = fs::read_to_string(&path).unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
        let updated = replace_marked_block(&original, &block).unwrap_or_else(|e| panic!("failed to update {}: {e}", path.display()));
        fs::write(&path, updated).unwrap_or_else(|e| panic!("failed to write {}: {e}", path.display()));
    }
}
